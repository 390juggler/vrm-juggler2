import {readFileSync,writeFileSync} from 'node:fs';

// Only search starting points are generated. A seed neither selects a technique
// nor certifies a trajectory; the runtime solves and validates the requested one.
const fixture=JSON.parse(readFileSync('test/fixtures/cross-generated-events.json','utf8').replace(/^\uFEFF/,''));
const shoulderY=1.4033702601,n=6;
const limits=[...Array.from({length:n},()=>[shoulderY-.42,shoulderY+.05]),
 ...Array.from({length:n},()=>[-.50,-.18]),[.65,1.22],[.65,1.05],[.45,1.35],...Array.from({length:8},()=>[-.16,.16])];
const seed=fixture.values.map((v,i)=>(v-limits[i][0])/(limits[i][1]-limits[i][0]));
// Upgrade the earlier Y/Z-only carry controls to X/Y/Z. A zero lateral
// displacement is the midpoint of its symmetric normalized interval.
const upgrade=s=>s.length===23?[...s.slice(0,15),...Array.from({length:4},(_,i)=>[.5,...s.slice(15+2*i,17+2*i)]).flat()]:s;
const seeds=[upgrade(seed)];
const inputs=process.argv.length>2?process.argv.slice(2):['docs/verification/sync-cross-search-solutions.json'];
for(const path of inputs)for(const row of JSON.parse(readFileSync(path,'utf8').replace(/^\uFEFF/,''))){
 if(row.ok&&row.skeleton?.skeletonOK&&Array.isArray(row.seed)&&row.seed.every(v=>Number.isFinite(v)&&v>=-1e-9&&v<=1+1e-9))seeds.push(upgrade(row.seed));
}
const unique=[...new Map(seeds.map(s=>[s.map(v=>v.toFixed(10)).join(','),s])).values()];
writeFileSync('src/motion/juggling/sync-search-seeds.ts',
 '// Generated by scripts/build-sync-search-seeds.mjs. Normalized numerical search candidates, not pattern definitions.\n'+
 'export const syncSearchSeeds:number[][]='+JSON.stringify(unique,null,2)+';\n');
